-- Serverseitiges Versandprotokoll fuer E-Mail-Hinweise zu neuen Mitteilungen.
-- Die Tabelle ist fuer App-Nutzer vollstaendig gesperrt und wird nur durch die
-- Edge Function mit dem serverseitigen Supabase-Schluessel verwendet.
create table public.message_email_deliveries (
  id bigint generated by default as identity primary key,
  message_id bigint not null references public.messages (id) on delete cascade,
  profile_id bigint not null references public.profiles (id) on delete cascade,
  status text not null default 'processing'
    check (status in ('processing', 'sent', 'failed')),
  attempt_count integer not null default 1 check (attempt_count > 0),
  last_attempt_at timestamp without time zone not null default now(),
  sent_at timestamp without time zone,
  brevo_message_id text,
  error_message text check (
    error_message is null or char_length(error_message) <= 500
  ),
  created_at timestamp without time zone not null default now(),
  updated_at timestamp without time zone not null default now(),
  constraint message_email_deliveries_message_profile_key
    unique (message_id, profile_id)
);

create index message_email_deliveries_status_attempt_idx
on public.message_email_deliveries (status, last_attempt_at);

alter table public.message_email_deliveries enable row level security;

revoke all on table public.message_email_deliveries from anon, authenticated;
grant select, insert, update on table public.message_email_deliveries
to service_role;
grant usage, select on sequence public.message_email_deliveries_id_seq
to service_role;

comment on table public.message_email_deliveries is
  'Private delivery and retry state for Brevo message notification emails.';

-- Ermittelt die E-Mail-Empfaenger anhand desselben fachlichen Empfaengerkreises
-- wie die Mitteilung: alle Elternkonten, ein Profil oder eine genehmigte Gruppe.
create or replace function public.list_message_email_recipients(
  target_message_id bigint
)
returns table (
  recipient_profile_id bigint,
  display_name text,
  email text
)
language sql
stable
security definer
set search_path = ''
as $$
  with target_message as (
    select
      academy_message.id,
      academy_message.audience,
      academy_message.recipient_profile_id,
      academy_message.group_id
    from public.messages as academy_message
    where academy_message.id = target_message_id
      and academy_message.published_at is not null
      and academy_message.published_at <= now()::timestamp without time zone
  ),
  recipient_profiles as (
    select account_role.profile_id
    from target_message as academy_message
    join public.user_roles as account_role
      on academy_message.audience = 'all'
      and account_role.role = 'parent'

    union

    select academy_message.recipient_profile_id
    from target_message as academy_message
    where academy_message.audience = 'profile'
      and academy_message.recipient_profile_id is not null

    union

    select child.parent_profile_id
    from target_message as academy_message
    join public.group_members as membership
      on academy_message.audience = 'group'
      and membership.group_id = academy_message.group_id
      and membership.membership_status = 'approved'
    join public.children as child on child.id = membership.child_id
  )
  select
    profile.id as recipient_profile_id,
    profile.display_name,
    auth_account.email::text
  from recipient_profiles as recipient
  join public.profiles as profile on profile.id = recipient.profile_id
  join auth.users as auth_account on auth_account.id = profile.auth_user_id
  where auth_account.email is not null
    and nullif(trim(auth_account.email::text), '') is not null
  order by profile.id;
$$;

revoke all on function public.list_message_email_recipients(bigint)
from public, anon, authenticated;
grant execute on function public.list_message_email_recipients(bigint)
to service_role;

-- Beansprucht einen Versand atomar. Bereits erfolgreich versendete oder gerade
-- laufende Zustellungen werden uebersprungen; fehlgeschlagene und verwaiste
-- Versuche koennen sicher erneut verarbeitet werden.
create or replace function public.claim_message_email_delivery(
  target_message_id bigint,
  target_profile_id bigint
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  claimed_delivery_id bigint;
begin
  insert into public.message_email_deliveries as delivery (
    message_id,
    profile_id,
    status,
    attempt_count,
    last_attempt_at
  )
  values (
    target_message_id,
    target_profile_id,
    'processing',
    1,
    now()::timestamp without time zone
  )
  on conflict (message_id, profile_id) do update
  set
    status = 'processing',
    attempt_count = delivery.attempt_count + 1,
    last_attempt_at = now()::timestamp without time zone,
    error_message = null,
    updated_at = now()::timestamp without time zone
  where delivery.status = 'failed'
    or (
      delivery.status = 'processing'
      and delivery.last_attempt_at
        < now()::timestamp without time zone - interval '15 minutes'
    )
  returning delivery.id into claimed_delivery_id;

  return claimed_delivery_id;
end;
$$;

revoke all on function public.claim_message_email_delivery(bigint, bigint)
from public, anon, authenticated;
grant execute on function public.claim_message_email_delivery(bigint, bigint)
to service_role;

